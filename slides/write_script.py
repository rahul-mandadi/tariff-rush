"""Write slides/SCRIPT.md from slides/speech.py.

The deck's speaker notes and this file now come from the same strings, so the printable script
and what is inside the pptx cannot say different things.

Usage:  python3 slides/write_script.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import speech

HEAD = {1: "Title", 2: "Every tariff comes with a date", 3: "The decision comes before the data",
        4: "So we ask three questions", 5: "What we have",
        6: "Unusual is not the same as tariffed", 7: "And this is where it nearly came apart",
        8: "Where we are"}

w = sum(len(speech.SPEAK[n].split()) for n in range(1, 9))
L = [
 "# Presentation 1, spoken script",
 "",
 "Generated from `slides/speech.py`. Do not edit this file, edit that one and re-run",
 "`python3 slides/write_script.py`. The deck's speaker notes come from the same place.",
 "",
 f"**{w} words.** At a careful 130 words a minute that is {speech.ms(w/130*60)}. At a normal",
 f"presenting pace of 145 it is {speech.ms(w/145*60)}. The per-slide times below assume 130, so",
 "they are the slow end. Rehearse once with a clock and find your own rate.",
 "",
 "**Split:** Rahul slides 1 to 4, Raunak slides 5 to 8. The rubric requires both to speak.",
 "",
 "Three sentences that must not be garbled:",
 "",
 '1. "If you label a product group tariffed when ninety-five percent of it wasn\'t, any real',
 '   reaction gets averaged away." (slide 7)',
 '2. "A price shock moves every country together so it cancels out. A tariff hits one country, so',
 '   it doesn\'t." (slide 8)',
 '3. "The rush doesn\'t start when a tariff becomes official. It starts when it becomes likely."',
 "   (slide 2)",
 "",
]
for n in range(1, 9):
    L += ["---", "",
          f"## {n}. {HEAD[n]}",
          "",
          f"**{speech.WHO[n]} · {speech.ms(speech.secs(n))} · clock at end {speech.ms(speech.clock(n))}**",
          "", speech.SPEAK[n], "",
          f"*{speech.CUE[n]}*", ""]

L += ["---", "", "## Clock", "",
      "| slide | who | this slide | clock at end |", "| --- | --- | --- | --- |"]
for n in range(1, 9):
    L.append(f"| {n} {HEAD[n].lower()} | {speech.WHO[n].title()} | "
             f"{speech.ms(speech.secs(n))} | {speech.ms(speech.clock(n))} |")
L += ["",
      f"**Hand over at {speech.ms(speech.clock(4))}.**",
      "",
      "If you are running long, these come out in this order and nothing else does:",
      "",
      "1. Slide 5, the \"how do we know the data's right\" sentence. 15 seconds.",
      "2. Slide 6, the organic chemicals sentence. 8 seconds.",
      "3. Slide 7, the three copper sentences. 15 seconds. The argument survives without copper;",
      "   it does not survive without the ninety-five percent sentence.",
      "",
      "Do not cut slide 4. It is the only slide that states the analytic problem, which the Context",
      "criterion scores explicitly, and slide 8's \"question one first\" dangles without it.",
      "", "---", "", "## If asked", ""]
for q, a in speech.QA:
    L += [f"**\"{q}\"**", "", a, ""]

open("slides/SCRIPT.md", "w").write("\n".join(L) + "\n")
print(f"wrote slides/SCRIPT.md  ({w} words, {speech.ms(speech.clock(8))} at 130 wpm)")
